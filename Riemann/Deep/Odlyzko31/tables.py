#!/usr/bin/env python3
"""odlyzko31: build TABLES.md / tables.csv from certified.json (output of certify.py) and odlyzko1976_tables12.csv."""
import json, math, sys
from math import gcd

def mobius(n):
    r, p = 1, 2
    while p * p <= n:
        if n % p == 0:
            n //= p
            if n % p == 0: return 0
            r = -r
        p += 1
    return -r if n > 1 else r

def phi(n):
    r, m, p = n, n, 2
    while p * p <= m:
        if m % p == 0:
            while m % p == 0: m //= p
            r -= r // p
        p += 1
    if m > 1: r -= r // m
    return r

def prim_counts(Q):
    """number of primitive Dirichlet characters of conductor q (all, even), q <= Q."""
    allc, even = {}, {}
    for q in range(1, Q + 1):
        a = sum(mobius(q // d) * phi(d) for d in range(1, q + 1) if q % d == 0)
        eps = mobius(q) + (mobius(q // 2) if q % 2 == 0 else 0)
        allc[q] = a; even[q] = (a + eps) // 2
    return allc, even

def elementary(n, counts):
    """rd >= (prod of the n smallest conductors of distinct primitive characters)^(1/n) for abelian fields of degree n."""
    s, k = 0.0, 0
    for q in sorted(counts):
        c = min(counts[q], n - k)
        s += c * math.log(q); k += c
        if k == n: return math.exp(s / n)
    return None

def main():
    d = json.load(open('certified.json'))
    R = {}
    for r in d['results']:
        if r['kind'] == 'table':
            R[(r['w'], r['n'], r['r1'])] = r['cert_rd']
    odl = {}
    for line in open('data/odlyzko1976_tables12.csv'):
        if line[0].isdigit():
            f = line.strip().split(','); odl[int(f[0])] = [float(x) if x else None for x in f[1:]]
    allc, even = prim_counts(4000)
    ns = sorted({n for (_, n, _) in R})
    L = []
    L.append('# odlyzko31 certified tables (generated by tables.py from certified.json)\n')
    L.append('Every entry c is certified in Arb: rd_K = |d_K|^{1/n} > c for every number field K of degree n of the stated kind '
             '(kernel and constants in certified.json). "all": formal r1 = 0, valid for every signature (Odlyzko\'s convention). '
             'classical = zeros anywhere in 0 < Re s < 1 (our recomputation, same kernels); 31/32 = Cureton-Thorner strip (every K); '
             'B = Bebel half-plane for Dirichlet L (abelian K; equally every K under Liu\'s unrefereed B_2); '
             'Odl76 = Odlyzko 1976 Tables 2 (unconditional) and 1 (GRH), valid for degree >= n; elem = conductor count for abelian K.\n')
    for kind, title in (('all', 'All signatures (formal r1 = 0)'), ('tr', 'Totally real (r1 = n)')):
        L.append(f'\n## {title}\n')
        L.append('| n | Odl76 uncond. | classical (ours) | 31/32 (ours) | gain vs classical | B, abelian (ours) | elem, abelian | Odl76 GRH |')
        L.append('|---|---|---|---|---|---|---|---|')
        for n in ns:
            r1 = 0 if kind == 'all' else n
            c, t, a = R.get(('classical', n, r1)), R.get(('ct', n, r1)), R.get(('ab', n, r1))
            if c is None or t is None: continue
            o = odl.get(n)
            ou = (o[2] if kind == 'tr' else o[3]) if o else None
            og = (o[0] if kind == 'tr' else o[1]) if o else None
            el = elementary(n, even if kind == 'tr' else allc) if (kind == 'tr' or n % 2 == 0) else None
            L.append(f'| {n} | {ou if ou else ""} | {c:.3f} | {t:.3f} | {100*(t/c-1):+.2f}% | {a:.3f} | {"" if el is None else f"{el:.3f}"} | {og if og else ""} |')
    # mixed signatures n <= 12 (31/32 and classical)
    L.append('\n## Mixed signatures, n <= 12\n')
    L.append('| n | r1 | 31/32 (every K) | classical | B (every K under Liu B_2; abelian K have r1 = 0 or n) |')
    L.append('|---|---|---|---|---|')
    for n in range(2, 13):
        for r1 in range(n % 2, n + 1, 2):
            if ('ct', n, r1) in R:
                L.append(f'| {n} | {r1} | {R[("ct", n, r1)]:.3f} | {R[("classical", n, r1)]:.3f} | {R[("ab", n, r1)]:.3f} |')
    lim = d['limits']
    L.append('\n## Limits n -> infinity (certified enclosures; sup over admissible kernels, attained by F = sech(w x))\n')
    L.append('| strip | w | A_r (totally real) | A_c (all signatures) |')
    L.append('|---|---|---|---|')
    for wk, wl in (('classical', '1/2'), ('ct', '15/32'), ('ab', '0.3733819666132076'), ('liu_arxiv', '0.374886647040')):
        L.append(f'| {wk} | {wl} | {lim[wk]["A_r"]} | {lim[wk]["A_c"]} |')
    L.append('| GRH | 0 | 215.33251 (8 pi e^{gamma + pi/2}) | 44.76323 (8 pi e^gamma) |')
    L.append('\n## Crossovers (certified in certify.py)\n')
    for r in d['results']:
        if r['kind'].startswith('cross_'):
            L.append(f"- {r['w']} {r['kind']}: n = {r['n']}, kernel {r['shape']}, b = {r['b']}: rd > {r['float_rd']:.6f}, beats classical limit: {r['beats_classical_limit']}")
    open('TABLES.md', 'w').write('\n'.join(L) + '\n')
    with open('tables.csv', 'w') as fo:
        fo.write('w,n,r1,shape,b,cert_rd,logA,logB,E\n')
        for r in d['results']:
            fo.write(f"{r['w']},{r['n']},{r['r1']},{r['shape']},{r['b']},{r['cert_rd']},{r['logA']:.12f},{r['logB']:.12f},{r['E']:.12e}\n")
    print('\n'.join(L[:6]))

if __name__ == '__main__':
    main()
