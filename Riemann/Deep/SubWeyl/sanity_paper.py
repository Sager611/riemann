import mpmath as mp
mp.mp.dps = 30
pi = mp.pi

def A3B3(eta, h):
    lam0 = (1/eta + 32*mp.sqrt(eta)*h/(15*mp.sqrt(pi)))**(-3)
    d3 = mp.sqrt(mp.mpf(1)/2 + mp.sqrt(1 + mp.mpf(3)/8*mp.sqrt(pi)*eta**1.5)/2)
    l03 = lam0**(mp.mpf(1)/3)
    A3 = mp.sqrt(1/(eta*h) + 32/(15*mp.sqrt(pi))*mp.sqrt(eta + l03) + (eta + l03)*l03/3)*d3
    B3 = mp.sqrt(32)/(mp.sqrt(3)*pi**0.25*eta**0.25)*d3
    return A3, B3

def delta(k, eta, variant=0):
    K = 2**(k-1)
    return mp.sqrt(1 + 2/mp.mpf(2337)**(1 - mp.mpf(2)/K)*(9*pi/1024*eta)**(mp.mpf(1)/K))

def AkBk(k, eta, h, variant=0):
    A, B = A3B3(eta, h)
    if variant == 1:  # use third-deriv delta_3 for the j=3 step
        d3 = mp.sqrt(mp.mpf(1)/2 + mp.sqrt(1 + mp.mpf(3)/8*mp.sqrt(pi)*eta**1.5)/2)
    for j in range(3, k):
        J = 2**(j-1)
        d = delta(j, eta)
        if variant == 1 and j == 3: d = d3
        A = d*(h**(-mp.mpf(1)/J) + 2**(mp.mpf(19)/12)*(J-1)/mp.sqrt((2*J-1)*(4*J-3))*mp.sqrt(A))
        B = d*2**1.5*(J-1)/mp.sqrt((2*J-3)*(4*J-5))*mp.sqrt(B)
    return A, B

def Kfun(t, th2, h1):
    return int(mp.ceil((mp.mpf(3)/34*mp.log(t) - mp.log(th2*mp.sqrt(2*pi)))/mp.log(h1)))

def Rfun(t, th2, th3, h2):
    return int(mp.ceil((mp.mpf(115)/1394*mp.log(t) - mp.log(th3/th2))/mp.log(h2)))

