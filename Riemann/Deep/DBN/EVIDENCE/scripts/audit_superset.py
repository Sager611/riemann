"""Independent rational auditor; imports no comparison producer.
DBN4 SUPERSET (generated by s6_superset_run.py from Planat's file, sha256 76bac79f402d25b727f52fb7add121acd45c55601383a4d8594238129cc04a0e):
all original checks kept; adds two-shift mixture records and optional exact geometry certificates.

Source inequalities and kernel inequalities have separate certificates.
This checks every consumed source, height, time join, self pair, outward
step, initial separation, and final ordinary strip allowance.
"""
from pathlib import Path
from fractions import Fraction as F
from collections import Counter
import argparse,copy,gzip,hashlib,json,time
def require(x,label):
    if not x:raise ValueError(label)
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def exp_upper(x):
    require(0<x<1,'Exponential argument')
    return sum(((-x)**k/F(__import__('math').factorial(k)) for k in range(21)),F(0))
def log_upper(z):
    require(0<z<1,'Logarithmic argument')
    w=z/(2+z)
    return 2*sum((w**(2*k+1)/F(2*k+1) for k in range(7)),F(0))+2*w**15/(15*(1-w*w))
def cap_ok(cap,r,v):
    R=r*r;A=cap;B=cap*(2*R-2)+2;C=cap*(1+R)**2-2*(1+R)
    require(A>0 and v>=0,'Own-pair range')
    vals=[C,A*v*v+B*v+C];vertex=-B/(2*A)
    if 0<vertex<v:vals.append(A*vertex*vertex+B*vertex+C)
    return min(vals)>=0
def audit(H,S,hashes,certs=None):
    require(H['schema'] in ('PLANAT_CLASSICAL_SOURCE_PORTFOLIO_V1','DBN4_MIXED_PORTFOLIO_V2'),'History schema')
    MK=H['mixed_kernels'] if H['schema']=='DBN4_MIXED_PORTFOLIO_V2' else []
    require(H['source_hashes']==hashes,'Source identities')
    require(H['uses_seven_eighths'] is False and H['uses_continuum_shift'] is False,'Scope')
    require(H['source_bounds_are_assumptions'] is True,'Analytic boundary')
    parts=H['parts'];require(type(parts)is int and parts>0,'Substeps')
    dt=F(1,4000*parts);q0=F(1000001,1000000)**2;q=q0;qe=F(1,10**8)
    require(F(H['initial_q'])==q0 and F(H['initial_strip_q'])==1 and F(H['terminal_q'])==qe,'Classical initial strip')
    providers=H['providers'];require(all(type(p)is int and p in (0,1)for p in providers),'Source providers')
    count=Counter();used=Counter();cache={};minimum_margin=None
    for pi in providers:
        source=S[pi]
        require(len(source['rows'])==len(source['plan']['rows'])==608,'Complete source schedule')
        require(source['frequency_pairs']==[[j,j]for j in range(6)]+[[j,j+1]for j in range(5)],'Frequency class coverage')
        for i,p in enumerate(source['plan']['rows']):
            require(p['time_index']==i and F(p['t_lo'])==F(i,4000) and F(p['t_hi'])==F(i+1,4000),'Closed source time cells')
    for n,rec in enumerate(H['records']):
        i,j=divmod(n,parts);now=n*dt
        require((rec['cell'],rec['sub'])==(i,j),'Contiguous time steps')
        if rec.get('type','single')=='single':
            pi=rec['provider'];ki=rec['kernel'];require(pi in providers and type(ki)is int and 0<=ki<H['kernel_count'],'Provider and kernel ownership')
            src=S[pi];h=F(src['plan']['rows'][i]['height']);k=src['kernels'][ki]
            r,rho,lam=(F(k[x])for x in ('r','rho','lambda'));v=q/h**2
            require(F(rec['q_in'])==q and F(rec['height'])==h,'Height and incoming state')
            require(v<=rho*rho and abs(h*r)<2,'Full kernel domain')
            margin=rho*rho-v;minimum_margin=margin if minimum_margin is None else min(minimum_margin,margin)
            mode='r_'+str(r).replace('/','_');ell=F(src['rows'][i][mode]);cap=F(k['self_cap'])
            require(F(rec['floor'])==ell and F(rec['self_cap'])==cap,'Whole source and own pair')
            require(cap_ok(cap,r,v),'Own-pair bound on entire decreasing range')
            if certs is not None:require(certs.kernel_ok(k),'Kernel geometry certificate')
            c=2*lam/h*(ell-cap/h)
            require(c==F(rec['rate']) and 0<c*dt<1,'Complete positive contraction rate')
            count[mode]+=1;used[str(pi)]+=1
        else:
            require(rec['type']=='mix' and H['schema']=='DBN4_MIXED_PORTFOLIO_V2','Record type')
            pi=rec['provider'];ki=rec['mix'];require(pi in providers and type(ki)is int and 0<=ki<len(MK),'Provider and mixture ownership')
            src=S[pi];h=F(src['plan']['rows'][i]['height']);m=MK[ki]
            require(m['id']==ki and m['cell']==i and m['provider']==pi,'Mixture cell and provider')
            r1,r2,rho,l1,l2=(F(m[x])for x in ('r1','r2','rho','lam1','lam2'));v=q/h**2
            require(F(rec['q_in'])==q and F(rec['height'])==h and F(m['height'])==h,'Height and incoming state')
            m1='r_'+str(r1).replace('/','_');m2='r_'+str(r2).replace('/','_')
            require(r1!=r2 and m1 in src['rows'][i] and m2 in src['rows'][i],'Declared fixed shifts')
            require(l1>=0 and l2>=0,'Mixture coefficient signs')
            require(0<rho<1 and v<=rho*rho and abs(h*r1)<2 and abs(h*r2)<2,'Full kernel domain')
            margin=rho*rho-v;minimum_margin=margin if minimum_margin is None else min(minimum_margin,margin)
            e1=F(src['rows'][i][m1]);e2=F(src['rows'][i][m2]);M1=F(m['cap1']);M2=F(m['cap2'])
            require(F(m['floor1'])==e1 and F(m['floor2'])==e2,'Whole source and own pair')
            require(cap_ok(M1,r1,v) and cap_ok(M2,r2,v),'Own-pair bound on entire decreasing range')
            if certs is not None:require(certs.mixture_ok(m),'Mixture geometry certificate')
            c=2/h*(l1*(e1-M1/h)+l2*(e2-M2/h))
            require(c==F(rec['rate']) and c==F(m['rate']) and 0<c*dt<1,'Complete positive contraction rate')
            mode='mix_'+m1+'+'+m2;ki=('mix',ki)
            count[mode]+=1;used[str(pi)]+=1
        if n==0:
            delay=F(H['initial_delay']);require(0<delay<dt and q0-(2+c*q0)*delay>1,'Strict classical time-zero separation')
        if 'terminal_lag_upper' in rec:
            z=c*(q-qe)/(2+c*qe);lag=F(rec['terminal_lag_upper'])
            require(log_upper(z)/c<=lag<=dt,'Independent terminal logarithm bound')
            U=F(H['upper_exact'])
            require(now+lag+qe/2<=U<F(41,250),'Terminal strip cost and wall range')
            require(n+1==len(H['records'])==H['steps'],'Complete history')
            require(dict(count)==H['shift_steps'] and dict(used)==H['provider_steps'],'Reported source partition')
            return {'schema':'PLANAT_CLASSICAL_PORTFOLIO_AUDIT_V1','PASS':True,'geometry_certificates_checked':certs is not None,'mixed_steps':sum(1 for x in H['records'] if x.get('type')=='mix'),
                    'label':H['label'],'steps':n+1,'upper_exact':str(U),
                    'upper_decimal':format(float(U),'.15f'),'provider_steps':dict(used),
                    'shift_steps':dict(count),'minimum_kernel_margin':str(minimum_margin),
                    'seven_eighths_assumed':False,'transcendentals_regenerated':False,
                    'physical_source_is_an_external_analytic_premise':True,
                    'independent_producer_imported':False}
        out=F(rec['q_out']);require(qe<out<q,'Positive decreasing restart')
        require((out*2**H['rounding_grid_bits']).denominator==1,'Declared dyadic lattice')
        key=(i,pi,ki)
        if key not in cache:cache[key]=exp_upper(c*dt)
        require(out>=(q+2/c)*cache[key]-2/c,'Independent outward exponential bound')
        q=out
    raise ValueError('No terminal record')
def negative_controls(H,S,hashes):
    changes=[('missing strip cushion',lambda h:h.update(initial_q='1')),
             ('changed source identity',lambda h:h['source_hashes'].__setitem__(0,'0'*64)),
             ('wrong provider',lambda h:h['records'][0].update(provider=1)),
             ('wrong physical height',lambda h:h['records'][0].update(height='1')),
             ('omitted own pair',lambda h:h['records'][0].update(self_cap='0')),
             ('inflated source floor',lambda h:h['records'][0].update(floor='100')),
             ('time gap',lambda h:h['records'][1].update(sub=2)),
             ('downward restart',lambda h:h['records'][0].update(q_out='1/10')),
             ('wrong external-strip status',lambda h:h.update(uses_seven_eighths=True))]
    out=[]
    for name,change in changes:
        h=copy.deepcopy(H);change(h)
        try:audit(h,S,hashes)
        except (ValueError,KeyError,IndexError) as e:out.append({'case':name,'rejected':True,'reason':str(e)})
        else:raise ValueError('Damaged history accepted: '+name)
    return {'PASS':True,'cases':out}
