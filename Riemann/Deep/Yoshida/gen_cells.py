# Generator of Riemann/Deep/Yoshida/Third.lean (stdlib only). Usage: python3 gen_cells.py 1/6 Third 1/32 18 0.0002 50 0.35 0.55 Third.lean
# Generate a Lean cell certificate for WeilPos(2a) (Riemann/Deep/Yoshida/Hybrid.lean, weilPos_of_cert).
# Units: W = 2 pi mu + J.  Cell (lo, hi, tau): need s - tau <= m(lo) + j(p) - Lam*d, p = mid, d = (hi-lo)/2.
# m(lo) = -G - LP - (1/4)/((1/4)^2+(lo/2)^2) + sum_{n<M} (1/(n+1) - (n+5/4)/((n+5/4)^2+(lo/2)^2))
# j(p) = 4(X/2 + p Y)/(1/4+p^2), X = SH*cl, Y = CH*sl (outward), cl = cosT(2K+2)(2ap), sl = sinT(2K+2)(2ap)
# final: 2a * sum tau*2(hi-lo) <= 2*3.14*s ; tail: s <= m(R) - 4(SH/(2R^2) + CH/R)
import sys, math
from fractions import Fraction as Fr
G, LP = Fr('0.5792'), Fr('1.1448')
KT = 4  # cos_ge KT / sin_ge KT : cosT (2KT+2)
def fl(x, q=10**6):  # round down
    return Fr(math.floor(x*q), q)
def cl_(x, q=10**6):
    return Fr(math.ceil(x*q), q)
def mval(lo, M):
    t2 = (lo/2)**2
    return -G - LP - Fr(1,4)/(Fr(1,16)+t2) + sum(Fr(1, n+1) - (n+Fr(5,4))/((n+Fr(5,4))**2 + t2) for n in range(M))
def cosT(n, x): return sum(Fr((-1)**k)*x**(2*k)/math.factorial(2*k) for k in range(n))
def sinT(n, x): return sum(Fr((-1)**k)*x**(2*k+1)/math.factorial(2*k+1) for k in range(n))
def expsum(x, n): return sum(x**m/math.factorial(m) for m in range(n))
def hyp(a, n=6):
    err = abs(a)**n*Fr(n+1, math.factorial(n)*n)
    ep, em = expsum(a, n), expsum(-a, n)
    sh_lo, sh_hi = ((ep-err)-(em+err))/2, ((ep+err)-(em-err))/2
    ch_lo, ch_hi = ((ep-err)+(em-err))/2, ((ep+err)+(em+err))/2
    return fl(sh_lo), cl_(sh_hi), fl(ch_lo), cl_(ch_hi)
def jval(a, p, SH, CH):
    sh_lo, sh_hi, ch_lo, ch_hi = SH + CH
    th = 2*a*p
    c = fl(cosT(2*KT+2, th)); s = fl(sinT(2*KT+2, th))
    X = (sh_lo if c >= 0 else sh_hi)*c
    Y = (ch_lo if s >= 0 else ch_hi)*s
    return fl(4*(X/2 + p*Y)/(Fr(1,4)+p*p)), c, s, X, Y
def plan(a, s, grid, R, pen, M, SH, CH, Lam):
    n = int(R/grid)
    pts = [grid*i for i in range(n+1)]
    mv = [float(mval(p, M)) for p in pts]
    best = [1e18]*(n+1); arg = [None]*(n+1); best[0] = 0
    sh_lo, sh_hi = SH; ch_lo, ch_hi = CH
    def jf(p):
        th = 2*float(a)*p
        return 4*(0.5*float(sh_lo)*math.cos(th) + p*float(ch_lo)*math.sin(th))/(0.25+p*p) - 1e-5
    for j in range(1, n+1):
        for i in range(max(0, j-48), j):
            lo, hi = pts[i], pts[j]
            w = mv[i] + jf(float(lo+hi)/2) - float(Lam)*float(hi-lo)/2
            t = max(0.0, float(s) - w)
            c = best[i] + 4*float(a)*t*float(hi-lo)/(2*math.pi) + pen
            if c < best[j]: best[j], arg[j] = c, i
    cells = []; j = n
    while j: cells.append((pts[arg[j]], pts[j])); j = arg[j]
    return cells[::-1]
def certify(a, s, cells, R, M, SH, CH, Lam):
    out = []; cost = Fr(0)
    for lo, hi in cells:
        p = (lo+hi)/2; d = (hi-lo)/2
        m = fl(mval(lo, M)); j, c, sn, X, Y = jval(a, p, SH, CH)
        tau = max(Fr(0), cl_(s - (m + j - Lam*d)))
        assert s - tau <= m + j - Lam*d
        out.append(dict(lo=lo, hi=hi, tau=tau, p=p, d=d, m=m, j=j, c=c, s=sn, X=X, Y=Y))
        cost += tau*2*(hi-lo)
    mR = fl(mval(R, M))
    tail = mR - 4*(SH[1]/(2*R*R) + CH[1]/R)
    ok_final = 2*a*cost <= 2*Fr('3.14')*s
    return out, cost, mR, tail, ok_final
def q(x):
    x = Fr(x)
    return f'({x.numerator} / {x.denominator} : ℝ)' if x.denominator != 1 else f'({x.numerator} : ℝ)'
def emit(name, a, s, R, M, cells, mR, SH, CH, Lam):
    sh_lo, sh_hi = SH; ch_lo, ch_hi = CH
    L = []
    w = L.append
    w('/-')
    w(f'Riemann/Deep/Yoshida/{name}.lean — GENERATED by .scratch/yoshida2/gen.py; do not edit.')
    w(f'Cell certificate for Weil positivity on the window 2a = {2*a} ({len(cells)} cells, s = {s}, R = {R}).')
    w('-/')
    w('import Riemann.Deep.Yoshida.Hybrid')
    w('')
    w('-- sequential elaboration: parallel elaboration of the cell lemmas costs ~1.5 GB extra memory')
    w('set_option Elab.async false')
    w('')
    w('noncomputable section')
    w('')
    w(f'namespace Fayed.Yoshida.{name}')
    w('')
    w('open Fayed.Yoshida Fayed.Yoshida.Taylor Finset')
    w('')
    A = q(a)
    w(f'lemma hyp : {q(sh_lo)} ≤ Real.sinh {A} ∧ Real.sinh {A} ≤ {q(sh_hi)} ∧')
    w(f'    {q(ch_lo)} ≤ Real.cosh {A} ∧ Real.cosh {A} ≤ {q(ch_hi)} := by')
    w(f'  have h1 := exp_mem (x := {A}) (by rw [abs_of_pos (by norm_num)]; norm_num) 6 (by norm_num)')
    w(f'  have h2 := exp_mem (x := -{A}) (by rw [abs_of_neg (by norm_num)]; norm_num) 6 (by norm_num)')
    w(f'  rw [abs_of_pos (by norm_num : (0 : ℝ) < {A})] at h1')
    w(f'  rw [abs_of_neg (by norm_num : -{A} < (0 : ℝ))] at h2')
    w('  norm_num [Finset.sum_range_succ, Nat.factorial] at h1 h2')
    w('  rw [Real.sinh_eq, Real.cosh_eq]')
    w('  refine ⟨?_, ?_, ?_, ?_⟩ <;> linarith [h1.1, h1.2, h2.1, h2.2]')
    w('')
    w(f'lemma hΛ : 8 * {A} ^ 2 * Real.cosh {A} ≤ {q(Lam)} := by')
    w(f'  have := hyp.2.2.2')
    w(f'  nlinarith')
    w('')
    for k, c in enumerate(cells):
        lo, hi, tau, p, d = c['lo'], c['hi'], c['tau'], c['p'], c['d']
        th = 2*a*p
        hX = 'mul_le_mul_of_nonneg_right hyp.1 (by norm_num)' if c['c'] >= 0 else 'mul_le_mul_of_nonpos_right hyp.2.1 (by norm_num)'
        hY = 'mul_le_mul_of_nonneg_right hyp.2.2.1 (by norm_num)' if c['s'] >= 0 else 'mul_le_mul_of_nonpos_right hyp.2.2.2 (by norm_num)'
        Xc = (sh_lo if c['c'] >= 0 else sh_hi); Yc = (ch_lo if c['s'] >= 0 else ch_hi)
        w(f'lemma cell{k} : CellOK {A} {q(s)} ({q(lo)}, {q(hi)}, {q(tau)}) := by')
        w(f'  have m : {q(c["m"])} ≤ 2 * Real.pi * Zeta23.mu {q(lo)} :=')
        w(f'    le_trans (by norm_num [Finset.sum_range_succ]) (two_pi_mu_ge {q(lo)} {M} euler_lt.le log_pi_lt.le)')
        w(f'  have hc : {q(c["c"])} ≤ Real.cos (2 * {A} * {q(p)}) :=')
        w(f'    le_trans (by norm_num [cosT, Finset.sum_range_succ, Nat.factorial]) (cos_ge {KT} (by norm_num))')
        w(f'  have hs : {q(c["s"])} ≤ Real.sin (2 * {A} * {q(p)}) :=')
        w(f'    le_trans (by norm_num [sinT, Finset.sum_range_succ, Nat.factorial]) (sin_ge {KT} (by norm_num))')
        w(f'  have j : {q(c["j"])} ≤ J {A} {q(p)} :=')
        w(f'    le_trans (by norm_num) (J_ge_of (X := {q(Xc)} * {q(c["c"])}) (Y := {q(Yc)} * {q(c["s"])})')
        w(f'      (by norm_num) (by norm_num) hc hs ({hX}) ({hY}))')
        w(f'  exact cellOK_of (d := {q(d)}) (by norm_num) (by norm_num) (by norm_num) (by norm_num)')
        w(f'    (by norm_num) (by norm_num) m j hΛ (by norm_num)')
        w('')
    lst = ', '.join(f'({q(c["lo"])}, {q(c["hi"])}, {q(c["tau"])})' for c in cells)
    w(f'def cells : List (ℝ × ℝ × ℝ) := [{lst}]')
    w('')
    w(f'lemma chain : Chain 0 cells {q(R)} := by')
    w('  norm_num [cells, Chain]')
    w('')
    w(f'lemma ok : ∀ c ∈ cells, CellOK {A} {q(s)} c := by')
    w('  simp only [cells, List.forall_mem_cons]')
    w('  exact ⟨' + ', '.join(f'cell{k}' for k in range(len(cells))) + ', fun _ h => by simp at h⟩')
    w('')
    w(f'lemma tail : ∀ r : ℝ, {q(R)} ≤ |r| → {q(s)} ≤ W {A} r := by')
    w(f'  have m : {q(mR)} ≤ 2 * Real.pi * Zeta23.mu {q(R)} :=')
    w(f'    le_trans (by norm_num [Finset.sum_range_succ]) (two_pi_mu_ge {q(R)} {M} euler_lt.le log_pi_lt.le)')
    w(f'  exact tail_of (by norm_num) (by norm_num) m hyp.2.1 hyp.2.2.2 (by norm_num)')
    w('')
    w(f'lemma final : 2 * {A} * cost cells ≤ 2 * Real.pi * {q(s)} := by')
    w('  have hπ := Real.pi_gt_d2')
    w('  norm_num [cells, cost]')
    w('  linarith')
    w('')
    w(f'/-- **Weil positivity on the window {2*a}** (generated certificate). -/')
    w(f'theorem weilPos : Riemann.Deep.Weil.WeilPos (2 * {A}) :=')
    w(f'  weilPos_of_cert (by norm_num) (by have := Real.log_two_gt_d9; norm_num at this ⊢; linarith)')
    w(f'    cells chain ok tail final')
    w('')
    w(f'end Fayed.Yoshida.{name}')
    return '\n'.join(L) + '\n'
if __name__ == '__main__':
    a = Fr(sys.argv[1]); name = sys.argv[2]; grid = Fr(sys.argv[3]); R = Fr(sys.argv[4]); pen = float(sys.argv[5])
    M = int(sys.argv[6]); smin, smax = float(sys.argv[7]), float(sys.argv[8])
    sh_lo, sh_hi, ch_lo, ch_hi = hyp(a)
    SH, CH = (sh_lo, sh_hi), (ch_lo, ch_hi)
    Lam = cl_(8*a*a*ch_hi)
    best = None
    for k in range(21):
        s = fl(smin + (smax-smin)*k/20, 1000)
        cells = plan(a, s, grid, R, pen, M, SH, CH, Lam)
        out, cost, mR, tail, okf = certify(a, s, cells, R, M, SH, CH, Lam)
        margin = float(2*Fr('3.14')*s - 2*a*cost)
        print(f's={float(s):.3f} cells={len(cells)} margin={margin:.4f} tail_ok={tail >= s} ({float(tail-s):.4f})', flush=True)
        if okf and tail >= s and (best is None or margin > best[0]):
            best = (margin, s, out, mR)
    if best is None: print('NO CERT'); sys.exit(1)
    margin, s, out, mR = best
    print('chosen s', s, 'cells', len(out), 'margin', margin)
    open(sys.argv[9], 'w').write(emit(name, a, s, R, M, out, mR, SH, CH, Lam))
