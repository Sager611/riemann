#!/usr/bin/env python3
"""indep_classes.py (unitaudit) -- independent enumeration of the closed relation sets of UnitCover DERIVATION sec 3.3.
Own algorithm: BFS over LATTICES generated by cube vectors {-1,0,1}^k containing no unit vector, keyed by a canonical
(fully reduced) row HNF built by extended-gcd insertion; Lambda <-> Lambda cap cube is a bijection with closed sets.
Elementary divisors by own Smith normal form.  Compares the class table (pi, k-rho, #d>1, prod d, count) with
cert.py classes(k).  Then brute force on groups: R(a) enumerated, #{a: R(a)=R} <= H^(k-rho) prod |G[d_i]|, and
|G_q[d]| <= 2 d^omega(q) for q <= 3000, d <= 64.  Writes logs/classes_k{1..4}.json for indep_union.py."""
import itertools, json, math, os, sys, time, random, importlib.util
sys.dont_write_bytecode = True          # no __pycache__ in UnitCover/ or ExplProgAudit/
from fractions import Fraction as Fr
t0 = time.time()

def egcd(a, b):
    if b == 0: return (a, 1, 0) if a >= 0 else (-a, -1, 0)
    g, x, y = egcd(b, a % b); return g, y, x - (a // b) * y

def insert(basis, v, k):
    """basis: dict pivot_col -> row (echelon).  Insert v into the Z-span; returns new dict (copy)."""
    B = dict((c, list(r)) for c, r in basis.items()); v = list(v)
    while any(v):
        c = next(j for j in range(k) if v[j])
        if c not in B:
            if v[c] < 0: v = [-x for x in v]
            B[c] = v; break
        r = B[c]; g, x, y = egcd(r[c], v[c])
        new = [x * a + y * bb for a, bb in zip(r, v)]                 # pivot g
        rest = [(v[c] // g) * a - (r[c] // g) * bb for a, bb in zip(r, v)]   # zero at c
        B[c] = new; v = rest
    return B

def canon(B, k):
    cols = sorted(B)
    rows = {c: list(B[c]) for c in cols}
    for c in cols:
        if rows[c][c] < 0: rows[c] = [-x for x in rows[c]]
    for i, c in enumerate(cols):            # reduce entries above each pivot into [0, pivot)
        for c2 in cols[:i]:
            qq = rows[c2][c] // rows[c][c]
            if qq: rows[c2] = [a - qq * bb for a, bb in zip(rows[c2], rows[c])]
    return tuple(tuple(rows[c]) for c in cols)

def member(B, v, k):
    return canon(insert(B, v, k), k) == canon(B, k)

def smith(M):
    """elementary divisors (all, incl. 1) of integer matrix M (rows x cols), own implementation"""
    A = [list(r) for r in M]; m = len(A); n = len(A[0]) if m else 0; ds = []
    t = 0
    while t < min(m, n):
        nz = [(abs(A[i][j]), i, j) for i in range(t, m) for j in range(t, n) if A[i][j]]
        if not nz: break
        _, i, j = min(nz)
        A[t], A[i] = A[i], A[t]
        for row in A: row[t], row[j] = row[j], row[t]
        done = False
        while not done:
            done = True
            for i in range(t + 1, m):
                if A[i][t]:
                    qq = A[i][t] // A[t][t]; A[i] = [a - qq * bb for a, bb in zip(A[i], A[t])]
                    if A[i][t]: done = False
            for j in range(t + 1, n):
                if A[t][j]:
                    qq = A[t][j] // A[t][t]
                    for row in A: row[j] -= qq * row[t]
                    if A[t][j]: done = False
            if not done:
                nz = [(abs(A[i][j]), i, j) for i in range(t, m) for j in range(t, n) if A[i][j] and (i == t or j == t)]
                _, i, j = min(nz); A[t], A[i] = A[i], A[t]
                for row in A: row[t], row[j] = row[j], row[t]
                continue
            bad = [(i, j) for i in range(t + 1, m) for j in range(t + 1, n) if A[i][j] % A[t][t]]
            if bad:
                i, j = bad[0]; A[t] = [a + bb for a, bb in zip(A[t], A[i])]; done = False
        ds.append(abs(A[t][t])); t += 1
    return ds

def lattices(k):
    cube = [e for e in itertools.product((-1, 0, 1), repeat=k) if any(e)]
    units = [tuple(int(i == j) for i in range(k)) for j in range(k)]
    start = {}
    seen = {canon(start, k): start}; frontier = [start]
    while frontier:
        nxt = []
        for B in frontier:
            for v in cube:
                B2 = insert(B, v, k); key = canon(B2, k)
                if key in seen: continue
                if any(member(B2, u, k) for u in units): seen[key] = None; continue   # mark rejected
                seen[key] = B2; nxt.append(B2)
        frontier = nxt
    return [B for B in seen.values() if B is not None]

def classes_own(k):
    cube0 = list(itertools.product((-1, 0, 1), repeat=k))
    agg = {}; sets = []
    for B in lattices(k):
        R = frozenset(e for e in cube0 if member(B, e, k))
        pi = sum(Fr(1, 2 ** (k + sum(1 for x in e if x))) for e in R)
        rho = len(B)
        ds = [d for d in smith(list(B.values())) if d > 1] if rho else []
        D = math.prod(ds) if ds else 1
        key = (pi, k - rho, len(ds), D); agg[key] = agg.get(key, 0) + 1
        sets.append((R, rho, tuple(ds), pi))
    return agg, sets

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("uc", os.path.join(HERE, "..", "UnitCover", "cert.py"))
uc = importlib.util.module_from_spec(spec); spec.loader.exec_module(uc)
SETS = {}
for k in (1, 2, 3, 4):
    agg, sets = classes_own(k); SETS[k] = sets
    theirs = {(pi, m, n, D): c for (pi, m, n, D, c) in uc.classes(k)}
    print("k=%d: own %d lattices/closed sets in %d classes; cert.py %d in %d classes; class tables identical: %s; max D = %d; max pi = %s"
          % (k, sum(agg.values()), len(agg), sum(theirs.values()), len(theirs), agg == theirs, max(x[3] for x in agg), max(x[0] for x in agg)), flush=True)
    own_sets = set(s[0] for s in sets); cert_sets = set(R for (_, _, _, R) in uc.closed_sets(k))
    print("   closed sets as sets identical to cert.py: %s" % (own_sets == cert_sets), flush=True)
    json.dump([[str(pi), m, n, D, c] for (pi, m, n, D), c in sorted(agg.items(), key=lambda x: (-x[0][1], x[0][0]))],
              open(os.path.join(HERE, "logs", "classes_k%d.json" % k), "w"))
print("enumeration done %.1f s" % (time.time() - t0), flush=True)

# brute force on groups G = prod Z/n_j (dual group ~ G): characters = vectors c
def check_group(ns, k, ntup=None, seed=1):
    H = math.prod(ns)
    elems = list(itertools.product(*[range(n) for n in ns]))
    nonprin = [c for c in elems if any(c)]
    cube0 = list(itertools.product((-1, 0, 1), repeat=k))
    idx = {s[0]: s for s in SETS[k]}
    cnt = {}
    rng = random.Random(seed)
    tuples = itertools.product(nonprin, repeat=k) if ntup is None else (tuple(rng.choice(nonprin) for _ in range(k)) for _ in range(ntup))
    nt = 0
    for a in tuples:
        nt += 1
        R = frozenset(e for e in cube0 if all(sum(ei * c[j] for ei, c in zip(e, a)) % ns[j] == 0 for j in range(len(ns))))
        if R not in idx: return "FAIL: R(a) not enumerated for %s" % (a,)
        cnt[R] = cnt.get(R, 0) + 1
    worst = 0
    for R, c in cnt.items():
        _, rho, ds, pi = idx[R]
        bound = H ** (k - rho) * math.prod(math.prod(math.gcd(d, n) for n in ns) for d in ds)
        if ntup is None and c > bound: return "FAIL count %d > %d" % (c, bound)
        worst = max(worst, c / bound)
    return "ok (%d tuples, %d distinct R, max count/bound %.3f)" % (nt, len(cnt), worst)
for ns, k, nt in [((2, 8), 4, None), ((12,), 4, None), ((2, 2, 2), 4, None), ((3, 3), 4, None), ((5,), 4, None),
                  ((2, 4, 8), 4, 20000), ((6, 6), 4, 20000), ((840,), 4, 20000), ((2, 2, 4, 3), 4, 20000), ((7, 7), 3, None)]:
    print("group Z/%s, k=%d: %s" % ("xZ/".join(map(str, ns)), k, check_group(ns, k, nt)), flush=True)

def Gd(q, d):
    """|{g in (Z/qZ)^x : g^d = 1}| by direct count"""
    return sum(1 for x in range(1, q) if math.gcd(x, q) == 1 and pow(x, d, q) == 1)
def omega(q):
    return sum(1 for p in range(2, q + 1) if q % p == 0 and all(p % r for r in range(2, int(p ** .5) + 1)))
bad = 0; worst = 0
for q in range(3, 1201):
    w = omega(q)
    for d in (2, 3, 4, 6, 8, 12, 16):
        g = Gd(q, d)
        if g > 2 * d ** w: bad += 1
        worst = max(worst, g / (2 * d ** w))
print("|G_q[d]| <= 2 d^omega(q) for 3 <= q <= 1200, d in {2,3,4,6,8,12,16}: violations %d, max ratio %.3f" % (bad, worst))
print("done %.1f s" % (time.time() - t0))
