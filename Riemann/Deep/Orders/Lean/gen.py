#!/usr/bin/env python3
"""gen.py - generates D_<order>.lean (patch data, base sequences, Theorem 2 per order) from
../patches.json and ../verify.py (exact search for the base range N0 <= N < N1).
Usage (repo root): python3 Riemann/Deep/Orders/Lean/gen.py"""
import os, sys
sys.dont_write_bytecode = True  # keep ../__pycache__ out of the repo
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import verify as V

OPS = {'+': '.add', 'x': '.mul', '-': '.sub', '/': '.div'}
NAME = {'+': 'p', 'x': 'x', '-': 'm', '/': 'd'}

def iv(n):
    return '(%d)' % n if n < 0 else '%d' % n

def lin(a, b):
    return '⟨%s, %s⟩' % (iv(a), iv(b))

def pmove(m):
    op, ta, tb, ua, ub, wa, wb = m
    return '⟨%s, %s, %s, %s⟩' % (OPS[op], lin(ta, tb), lin(ua, ub), lin(wa, wb))

def lst(items, ind='    '):
    if not items:
        return '[]'
    return '[' + (',\n' + ind).join(items) + ']'

def name(o):
    return ''.join(NAME[ch] for ch in o)

def gen(o, D):
    r, N0, N1 = D['r'], D['N0'], D['N1']
    offs = sorted(int(c) for c in D['patches'])
    nm = name(o)
    out = ['import Riemann.Deep.Orders.Lean.Induct', '',
           '/-! Generated by gen.py: order %s (patches.json, base sequences from verify.py search). -/'
           % ' '.join({'+': '+', 'x': '×', '-': '−', '/': '÷'}[ch] for ch in o),
           'namespace Orders.D_%s' % nm, 'open Orders', '',
           'def ord : Order := ⟨%s⟩' % ', '.join(OPS[ch] for ch in o), '']
    for c in offs:
        e = D['patches'][str(c)]
        mv = e['moves']
        out.append('def p%d : Patch := ⟨%d, %d,\n  %s,\n  %s⟩' % (
            c, e['d'], e['qstar'], lst([pmove(m) for m in mv[:12]], '   '),
            lst([pmove(m) for m in mv[12:]], '   ')))
        out.append('')
    out.append('def pt : Nat → Patch')
    for c in offs[:-1]:
        out.append('  | %d => p%d' % (c, c))
    out.append('  | _ => p%d' % offs[-1])
    out.append('')
    out.append('def offs : List Nat := [%s]' % ', '.join(map(str, offs)))
    out.append('')
    out.append('theorem ord_perm : ord.IsPerm := by unfold Order.IsPerm; decide')
    out.append('')
    for c in offs:
        out.append('theorem ok%d : patchOK ord %d %d (pt %d) = true := by decide +kernel' % (c, r, c, c))
    out.append('')
    out.append('theorem patches_ok : ∀ c ∈ offs, patchOK ord %d c (pt c) = true := by' % r)
    out.append('  intro c hc')
    out.append('  simp only [offs, List.mem_cons, List.not_mem_nil, or_false] at hc')
    out.append('  rcases hc with ' + ' | '.join(['rfl'] * len(offs)))
    for c in offs:
        out.append('  · exact ok%d' % c)
    out.append('')
    for N in range(N0, N1):
        s = V.search(o, N)
        assert s is not None and V.check(o, s, N) is None, (o, N)
        out.append('def s%d : List Move := [' % N + ', '.join('⟨%d, %d, %d⟩' % (x, y, v) for (x, op, y, v) in s) + ']')
        out.append('theorem b%d : check ord %d s%d = true := by decide +kernel' % (N, N, N))
    out.append('')
    out.append('theorem base : ∀ N, %d ≤ N → N < %d → ∃ ms, Perfect ord N ms := by' % (N0, N1))
    out.append('  intro N h1 h2')
    out.append('  rcases (by omega : ' + ' ∨ '.join('N = %d' % N for N in range(N0, N1)) + ') with ' + ' | '.join(['rfl'] * (N1 - N0)))
    for N in range(N0, N1):
        out.append('  · exact ⟨_, (check_iff _ _ _).1 b%d⟩' % N)
    out.append('')
    out.append('theorem cov : ∀ N, %d ≤ N → ∃ c ∈ offs, ∃ q, N = 3 * (4 * q + %d) + c ∧ (pt c).qstar ≤ q ∧ %d ≤ 4 * q + %d := by' % (N1, r, N0, r))
    out.append('  intro N hN')
    out.append('  rcases (by omega : ' + ' ∨ '.join('N %% 12 = %d' % k for k in range(12)) + ') with ' + ' | '.join(['h'] * 12))
    for rho in range(12):
        c = next(c for c in offs if (3 * r + c) % 12 == rho)
        qs = D['patches'][str(c)]['qstar']
        # check the omega obligations numerically on the least N >= N1 in the class
        Nl = next(N for N in range(N1, N1 + 12) if N % 12 == rho)
        q = (Nl - c - 3 * r) // 12
        assert Nl == 3 * (4 * q + r) + c and qs <= q and N0 <= 4 * q + r, (o, rho)
        out.append('  · exact ⟨%d, by decide, (N - %d) / 12, by omega, Nat.le_trans (by decide : (pt %d).qstar ≤ %d) (by omega), by omega⟩' % (c, c + 3 * r, c, qs))
    out.append('')
    out.append('/-- Theorem 2 for this order: a perfect sequence for every N ≥ %d. -/' % N0)
    out.append('theorem works : ∀ N, %d ≤ N → ∃ ms, Perfect ord N ms :=' % N0)
    out.append('  works_of ord_perm %d %d %d (by decide) pt offs patches_ok' % (r, N0, N1))
    out.append('    base cov')
    out.append('')
    out.append('end Orders.D_%s' % nm)
    return nm, '\n'.join(out) + '\n'

if __name__ == '__main__':
    only = sys.argv[1:]
    for o, D in V.DATA.items():
        nm, txt = gen(o, D)
        if only and nm not in only:
            continue
        open(os.path.join(HERE, 'D_%s.lean' % nm), 'w').write(txt)
        print(nm, len(txt.splitlines()), 'lines', len(txt), 'bytes')

