
import json
d = json.load(open('Riemann/Deep/GL2Ceil/logs/ceil_25_256_0.07005633.json'))
cells = d['cells']
assert d['xi'] == '25/256' and d['kappa_up'] == '0.07005633' and d['certified']
assert abs(d['HL'] - 2**-20) < 1e-30
out = []
out.append("import Riemann.Deep.GL2Ceil.Lean.Bernard\n")
out.append("/-!\n# GL2Ceil (gl2lean): the cell list of logs/ceil_25_256_0.07005633.json\n\nGenerated by .scratch/gl2lean/gen_cells.py from the JSON (fields R centre, R half-width, λ_lo, λ_hi in\nunits of 2^{-20}, kind). The named hypotheses Cover, CertCells are then literally about these cells.\n-/\n")
out.append("namespace GL2Ceil\n")
chunks = [cells[i:i+100] for i in range(0, len(cells), 100)]
names = []
for k, ch in enumerate(chunks):
    nm = f"cells{k}"
    names.append(nm)
    out.append(f"/-- cells {100*k}..{100*k+len(ch)-1} -/\ndef {nm} : List Cell := [")
    items = []
    for (rc, dr, l0, l1, kind) in ch:
        assert kind in ('dual', 'crude')
        items.append(f"  ⟨{rc}, {dr}, {l0}, {l1}, {'true' if kind=='dual' else 'false'}⟩")
    out.append(",\n".join(items) + "]\n")
out.append("/-- The 1276 cells (1257 dual, 19 crude) of the certified run. -/\ndef jsonCells : List Cell := " + " ++ ".join(names) + "\n")
nd = sum(1 for c in cells if c[4]=='dual'); nc = len(cells) - nd
out.append(f"theorem jsonCells_length : jsonCells.length = {len(cells)} := by decide +kernel\n")
out.append(f"theorem jsonCells_dual : (jsonCells.filter (fun c => c.dual)).length = {nd} := by decide +kernel\n")
out.append("""
/-- Main theorem, Bernard's literal class, with the named hypotheses about the JSON cells. -/
theorem ceiling_bernard_json (hcov : Cover jsonCells) (hcert : CertCells jsonCells)
    (hS : TailSmallR) (hL : TailLargeLam) (hR : TailLargeR)
    (P : Polynomial ℝ) (hP0 : P.eval 0 = 0) (hP1 : P.eval 1 = 1) (M : ℕ) (lam : ℕ → ℝ)
    {R ξ : ℝ} (hR0 : 0 < R) (hξ : 0 < ξ) (hξ0 : ξ ≤ 25 / 256) :
    kappaC (fun x => P.eval x) (QB M lam) R ξ ≤ 0.07005633 :=
  ceiling_bernard jsonCells hcov hcert hS hL hR P hP0 hP1 M lam hR0 hξ hξ0

end GL2Ceil
""")
open('Riemann/Deep/GL2Ceil/Lean/Cells.lean','w').write("\n".join(out))
print(len(cells), nd, nc, len(chunks))

